// Looping incoming call ringtone
let ringtoneInterval: number | null = null;

export function startRingtone() {
  stopRingtone();
  const ring = () => {
    const ctx = getAudioContext();
    if (!ctx) return;
    try {
      const playChirp = (freq: number, start: number, dur: number) => {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(freq, ctx.currentTime + start);
        gain.gain.setValueAtTime(0.18, ctx.currentTime + start);
        gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + start + dur);
        osc.connect(gain);
        gain.connect(ctx.destination);
        osc.start(ctx.currentTime + start);
        osc.stop(ctx.currentTime + start + dur);
      };

      playChirp(750, 0, 0.2);
      playChirp(900, 0.22, 0.3);
      playChirp(750, 0.65, 0.2);
      playChirp(900, 0.87, 0.3);
    } catch {
      // Ignore audio error
    }
  };

  ring();
  ringtoneInterval = window.setInterval(ring, 2200);
}

export function stopRingtone() {
  if (ringtoneInterval !== null) {
    clearInterval(ringtoneInterval);
    ringtoneInterval = null;
  }
}

// Outgoing calling ringback tone
let ringbackInterval: number | null = null;
export function startRingbackTone() {
  stopRingbackTone();
  const ringback = () => {
    const ctx = getAudioContext();
    if (!ctx) return;
    try {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = 'sine';
      osc.frequency.setValueAtTime(440, ctx.currentTime);
      gain.gain.setValueAtTime(0.08, ctx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 1.2);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start();
      osc.stop(ctx.currentTime + 1.2);
    } catch {
      // Ignore
    }
  };
  ringback();
  ringbackInterval = window.setInterval(ringback, 3000);
}

export function stopRingbackTone() {
  if (ringbackInterval !== null) {
    clearInterval(ringbackInterval);
    ringbackInterval = null;
  }
}

// Call ended sound
export function playCallEndSound() {
  stopRingtone();
  stopRingbackTone();
  const ctx = getAudioContext();
  if (!ctx) return;
  try {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(320, ctx.currentTime);
    osc.frequency.setValueAtTime(200, ctx.currentTime + 0.15);
    gain.gain.setValueAtTime(0.12, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.3);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start();
    osc.stop(ctx.currentTime + 0.3);
  } catch {
    // Ignore
  }
}
